-- v2.3 production-commerce features (shipping enhancements intentionally excluded)
ALTER TABLE orders ADD COLUMN IF NOT EXISTS cancelled_at TIMESTAMPTZ;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS refund_status VARCHAR(30) NOT NULL DEFAULT 'none';
ALTER TABLE orders ADD COLUMN IF NOT EXISTS refund_amount_cents INT NOT NULL DEFAULT 0;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS refunded_at TIMESTAMPTZ;
CREATE TABLE IF NOT EXISTS order_status_history (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id INTEGER NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
 status VARCHAR(40) NOT NULL, note TEXT, actor VARCHAR(30) NOT NULL DEFAULT 'system', created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS order_status_history_order_idx ON order_status_history(order_id,created_at);
ALTER TABLE coupons ADD COLUMN IF NOT EXISTS max_uses INT;
ALTER TABLE coupons ADD COLUMN IF NOT EXISTS per_customer_limit INT NOT NULL DEFAULT 1;
ALTER TABLE coupons ADD COLUMN IF NOT EXISTS used_count INT NOT NULL DEFAULT 0;
CREATE TABLE IF NOT EXISTS coupon_redemptions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 coupon_id INTEGER NOT NULL REFERENCES coupons(id) ON DELETE CASCADE,
 user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
 order_id INTEGER UNIQUE REFERENCES orders(id) ON DELETE CASCADE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS product_variants (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 product_id INTEGER NOT NULL REFERENCES products(id) ON DELETE CASCADE,
 name VARCHAR(120) NOT NULL, sku VARCHAR(100) UNIQUE, price_cents INT CHECK(price_cents>=0), stock_qty INT NOT NULL DEFAULT 0 CHECK(stock_qty>=0), active BOOLEAN NOT NULL DEFAULT true
);
CREATE TABLE IF NOT EXISTS notification_outbox (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
 order_id INTEGER REFERENCES orders(id) ON DELETE SET NULL,
 channel VARCHAR(20) NOT NULL, template VARCHAR(60) NOT NULL, recipient TEXT NOT NULL,
 payload JSONB NOT NULL DEFAULT '{}'::jsonb, status VARCHAR(20) NOT NULL DEFAULT 'pending', created_at TIMESTAMPTZ NOT NULL DEFAULT now(), sent_at TIMESTAMPTZ
);
CREATE TABLE IF NOT EXISTS audit_logs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 actor_type VARCHAR(30) NOT NULL, actor_id TEXT, action VARCHAR(100) NOT NULL, entity_type VARCHAR(60), entity_id TEXT, metadata JSONB NOT NULL DEFAULT '{}'::jsonb, created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
