CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  phone VARCHAR(20) UNIQUE NOT NULL,
  name VARCHAR(120), email VARCHAR(255), role VARCHAR(20) NOT NULL DEFAULT 'customer',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS categories (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL, slug VARCHAR(140) UNIQUE NOT NULL,
  type VARCHAR(30) NOT NULL CHECK (type IN ('gemstone','jewellery')),
  image_url TEXT, description TEXT, sort_order INT NOT NULL DEFAULT 0, active BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS products (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, category_id INTEGER REFERENCES categories(id) ON DELETE SET NULL,
  name VARCHAR(180) NOT NULL, slug VARCHAR(200) UNIQUE NOT NULL, sku VARCHAR(80) UNIQUE,
  description TEXT, note TEXT, stone VARCHAR(140), metal VARCHAR(120), image_url TEXT NOT NULL,
  price_cents INT NOT NULL CHECK(price_cents >= 0), compare_at_cents INT, stock_qty INT NOT NULL DEFAULT 0,
  featured BOOLEAN NOT NULL DEFAULT false, active BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS product_images (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, product_id INTEGER NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  image_url TEXT NOT NULL, alt_text TEXT, sort_order INT NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS addresses (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  first_name VARCHAR(80), last_name VARCHAR(80), line1 TEXT NOT NULL, line2 TEXT, city VARCHAR(100), state VARCHAR(100), postal_code VARCHAR(20), country VARCHAR(80) DEFAULT 'India', phone VARCHAR(20)
);
CREATE TABLE IF NOT EXISTS orders (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_number VARCHAR(30) UNIQUE NOT NULL,
  user_id INTEGER REFERENCES users(id) ON DELETE SET NULL, status VARCHAR(30) NOT NULL DEFAULT 'placed',
  payment_status VARCHAR(30) NOT NULL DEFAULT 'pending', payment_method VARCHAR(40),
  subtotal_cents INT NOT NULL, shipping_cents INT NOT NULL DEFAULT 0, discount_cents INT NOT NULL DEFAULT 0, total_cents INT NOT NULL,
  shipping_address JSONB NOT NULL DEFAULT '{}'::jsonb, created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS order_items (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id INTEGER NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  product_id INTEGER REFERENCES products(id) ON DELETE SET NULL, product_name VARCHAR(180) NOT NULL, sku VARCHAR(80),
  unit_price_cents INT NOT NULL, quantity INT NOT NULL CHECK(quantity > 0), image_url TEXT
);
CREATE TABLE IF NOT EXISTS coupons (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code VARCHAR(50) UNIQUE NOT NULL, discount_type VARCHAR(20) NOT NULL CHECK(discount_type IN ('percent','fixed')),
  discount_value INT NOT NULL, min_order_cents INT DEFAULT 0, active BOOLEAN DEFAULT true, starts_at TIMESTAMPTZ, ends_at TIMESTAMPTZ
);
CREATE TABLE IF NOT EXISTS content_blocks (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, block_key VARCHAR(120) UNIQUE NOT NULL, title TEXT, subtitle TEXT, body TEXT, image_url TEXT, cta_label TEXT, cta_url TEXT, active BOOLEAN DEFAULT true, updated_at TIMESTAMPTZ DEFAULT now()
);


-- SEO and analytics configuration
CREATE TABLE IF NOT EXISTS seo_pages (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  path VARCHAR(240) UNIQUE NOT NULL,
  title VARCHAR(180) NOT NULL,
  description TEXT,
  keywords TEXT,
  og_title VARCHAR(180),
  og_description TEXT,
  og_image TEXT,
  active BOOLEAN NOT NULL DEFAULT true,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS site_settings (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  setting_key VARCHAR(120) UNIQUE NOT NULL,
  setting_value TEXT NOT NULL DEFAULT '',
  description TEXT,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
