-- Run in a transaction before schema.sql. Legacy UUIDs are retained for reference.
DO $$
DECLARE t RECORD; fk RECORD; col RECORD; pk TEXT;
BEGIN
 IF EXISTS(SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='products' AND column_name='id' AND data_type='uuid') THEN
  CREATE TEMP TABLE migration_foreign_keys ON COMMIT DROP AS
   SELECT c.conrelid::regclass::text AS child, c.confrelid::regclass::text AS parent,
          a.attname AS column_name, c.conname, pg_get_constraintdef(c.oid) AS definition
   FROM pg_constraint c JOIN pg_attribute a ON a.attrelid=c.conrelid AND a.attnum=c.conkey[1]
   WHERE c.contype='f' AND c.connamespace='public'::regnamespace;
  FOR t IN SELECT table_name FROM information_schema.columns WHERE table_schema='public' AND column_name='id' AND data_type='uuid' LOOP
   EXECUTE format('ALTER TABLE %I ADD COLUMN numeric_id INTEGER GENERATED BY DEFAULT AS IDENTITY',t.table_name);
  END LOOP;
  FOR fk IN SELECT * FROM migration_foreign_keys LOOP
   EXECUTE format('ALTER TABLE %I ADD COLUMN %I INTEGER',fk.child,'numeric_'||fk.column_name);
   EXECUTE format('UPDATE %I c SET %I=p.numeric_id FROM %I p WHERE c.%I=p.id',fk.child,'numeric_'||fk.column_name,fk.parent,fk.column_name);
   IF EXISTS(SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name=fk.child AND column_name=fk.column_name AND is_nullable='NO') THEN
    EXECUTE format('ALTER TABLE %I ALTER COLUMN %I SET NOT NULL',fk.child,'numeric_'||fk.column_name);
   END IF;
   EXECUTE format('ALTER TABLE %I DROP CONSTRAINT %I',fk.child,fk.conname);
  END LOOP;
  FOR t IN SELECT table_name FROM information_schema.columns WHERE table_schema='public' AND column_name='id' AND data_type='uuid' LOOP
   SELECT conname INTO pk FROM pg_constraint WHERE conrelid=format('%I',t.table_name)::regclass AND contype='p';
   EXECUTE format('ALTER TABLE %I DROP CONSTRAINT %I',t.table_name,pk);
   EXECUTE format('ALTER TABLE %I RENAME COLUMN id TO legacy_id',t.table_name);
   EXECUTE format('ALTER TABLE %I RENAME COLUMN numeric_id TO id',t.table_name);
   EXECUTE format('ALTER TABLE %I ADD PRIMARY KEY(id)',t.table_name);
   EXECUTE format('ALTER TABLE %I ADD UNIQUE(legacy_id)',t.table_name);
  END LOOP;
  FOR fk IN SELECT * FROM migration_foreign_keys LOOP
   EXECUTE format('ALTER TABLE %I DROP COLUMN %I',fk.child,fk.column_name);
   EXECUTE format('ALTER TABLE %I RENAME COLUMN %I TO %I',fk.child,'numeric_'||fk.column_name,fk.column_name);
   EXECUTE format('ALTER TABLE %I ADD CONSTRAINT %I %s',fk.child,fk.conname,fk.definition);
  END LOOP;
  ALTER TABLE wishlists ADD CONSTRAINT wishlists_user_product_unique UNIQUE(user_id,product_id);
 END IF;
 FOR col IN SELECT table_name,column_name FROM information_schema.columns WHERE table_schema='public' AND column_name LIKE '%\_paise' ESCAPE '\' LOOP
  EXECUTE format('ALTER TABLE %I RENAME COLUMN %I TO %I',col.table_name,col.column_name,replace(col.column_name,'_paise','_cents'));
 END LOOP;
 IF to_regclass('public.settings') IS NOT NULL THEN
  UPDATE settings SET key=replace(key,'_paise','_cents'),description=replace(description,'paise','USD cents') WHERE key LIKE '%paise';
 END IF;
END $$;
